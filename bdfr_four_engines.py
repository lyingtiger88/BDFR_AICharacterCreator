"""BDFR four-engine integration, v0.3.0.
Adapters to EXISTING MakeHuman, SMPL-X, EOS and mGear products.
No synthetic body meshes are generated by this module.
"""
from __future__ import annotations
import os
import shutil
import subprocess
import importlib.util
from pathlib import Path

def status():
    """Detect local installations without downloading proprietary model data."""
    return {
        "makehuman": "Use exported OBJ/FBX from MakeHuman",
        "smplx_python": importlib.util.find_spec("smplx") is not None,
        "eos_python": importlib.util.find_spec("eos") is not None,
        "eos_fit_model": shutil.which("fit-model-simple") or shutil.which("fit-model"),
        "mgear_python": importlib.util.find_spec("mgear") is not None,
    }

def import_makehuman(filepath, namespace="BDFR"):
    """Use a REAL exported MakeHuman character as the base, including limbs."""
    import maya.cmds as cmds
    path=Path(filepath).expanduser().resolve()
    if not path.is_file() or path.suffix.lower() not in {".obj",".fbx"}:
        raise ValueError("Choose an existing MakeHuman .obj or .fbx export.")
    old=set(cmds.ls(assemblies=True,long=True) or [])
    if path.suffix.lower()==".fbx":
        cmds.loadPlugin("fbxmaya",quiet=True)
        cmds.file(str(path),i=True,type="FBX",ignoreVersion=True,
                  mergeNamespacesOnClash=False,namespace=namespace,
                  options="fbx",preserveReferences=True)
    else:
        cmds.loadPlugin("objExport",quiet=True)
        cmds.file(str(path),i=True,type="OBJ",ignoreVersion=True,
                  mergeNamespacesOnClash=False,namespace=namespace,
                  options="mo=1",preserveReferences=True)
    new=list(set(cmds.ls(assemblies=True,long=True) or [])-old)
    if not new:
        raise RuntimeError("Import completed but no new root nodes were found. Inspect Maya Outliner.")
    meshes=[]
    for root in new:
        meshes.extend(cmds.listRelatives(root,ad=True,type="mesh",fullPath=True) or [])
        meshes.extend(cmds.listRelatives(root,shapes=True,type="mesh",fullPath=True) or [])
    if not meshes:
        raise RuntimeError("MakeHuman import contains no polygon mesh.")
    return {"roots":sorted(new),"mesh_count":len(set(meshes))}

def eos_fit_from_photo(image, landmarks, model, mapping, exe="fit-model-simple",
                       output_dir=None):
    """Runs the existing EOS example binary. Requires externally produced iBUG landmarks.
    No claim of AI landmark detection; output is EOS face OBJ + texture.
    """
    required=[image,landmarks,model,mapping]
    for f in required:
        if not Path(f).is_file():
            raise FileNotFoundError(str(f))
    executable=shutil.which(exe) or (str(Path(exe).resolve()) if Path(exe).is_file() else None)
    if not executable:
        raise FileNotFoundError("EOS executable not found. Build EOS fit-model-simple first.")
    directory=Path(output_dir or Path(image).parent).resolve()
    directory.mkdir(parents=True,exist_ok=True)
    args=[executable,"-m",str(Path(model).resolve()),"-p",str(Path(mapping).resolve()),
          "-i",str(Path(image).resolve()),"-l",str(Path(landmarks).resolve())]
    result=subprocess.run(args,cwd=str(directory),capture_output=True,text=True,timeout=180)
    if result.returncode:
        raise RuntimeError("EOS fitting failed: "+result.stderr[-3000:])
    return {"working_directory":str(directory),"stdout":result.stdout[-3000:]}

def check_smplx_assets(model_directory):
    """Validate prerequisites; model license/download remain user-controlled."""
    d=Path(model_directory).expanduser()
    if not d.is_dir():
        raise FileNotFoundError("SMPL-X model directory is missing: "+str(d))
    candidates=list(d.rglob("SMPLX_*.npz"))+list(d.rglob("SMPLX_*.pkl"))
    if not candidates:
        raise FileNotFoundError("No SMPLX_*.npz or SMPLX_*.pkl found.")
    if importlib.util.find_spec("smplx") is None:
        return {"models":[str(p) for p in candidates],"python_package":False,
                "note":"Install smplx in a compatible external Python environment."}
    return {"models":[str(p) for p in candidates],"python_package":True}

def mgear_status():
    """Check Maya's environment; actual rig build requires a compatible guide."""
    try:
        import mgear
        return {"installed":True,"location":getattr(mgear,"__file__",None),
                "note":"Importing mGear does not auto-rig MakeHuman geometry."}
    except (ImportError,ModuleNotFoundError) as exc:
        return {"installed":False,"reason":str(exc)}

def launch():
    """Maya-native bridge UI. All buttons connect to actual adapters."""
    import maya.cmds as cmds
    name="BDFR_4Engines"
    if cmds.window(name,exists=True):
        cmds.deleteUI(name)
    win=cmds.window(name,title="BDFR Character Creator | 4 Engines v0.3",
                    sizeable=True,widthHeight=(470,400))
    cmds.columnLayout(adjustableColumn=True,rowSpacing=9)
    cmds.text(label="MAKEHUMAN  /  SMPL-X  /  EOS  /  mGEAR",font="boldLabelFont",height=36)
    cmds.text(label="Import real MakeHuman character. No procedural mannequin.",align="center")
    cmds.separator(style="in")
    def do_import(*_):
        paths=cmds.fileDialog2(fileMode=1,caption="Select MakeHuman OBJ or FBX",
                              fileFilter="Character (*.obj *.fbx)")
        if paths:
            try:
                result=import_makehuman(paths[0])
                cmds.confirmDialog(title="MakeHuman imported",
                                   message="Meshes: "+str(result["mesh_count"])+"\nRoots: "+str(result["roots"]),
                                   button=["OK"])
            except Exception as exc:
                cmds.confirmDialog(title="Import error",message=str(exc),button=["OK"])
                raise
    cmds.button(label="1  IMPORT MAKEHUMAN CHARACTER (.OBJ / .FBX)",height=45,command=do_import)
    cmds.separator(style="in")
    model=cmds.textFieldButtonGrp(label="SMPL-X models",buttonLabel="Browse",adjustableColumn=2)
    def choose_models(*_):
        selected=cmds.fileDialog2(fileMode=3,caption="SMPL-X license-provided model folder")
        if selected: cmds.textFieldButtonGrp(model,e=True,text=selected[0])
    cmds.textFieldButtonGrp(model,e=True,buttonCommand=choose_models)
    def check_models(*_):
        try:
            r=check_smplx_assets(cmds.textFieldButtonGrp(model,q=True,text=True))
            cmds.confirmDialog(title="SMPL-X",message=str(r)[:1000],button=["OK"])
        except Exception as exc:
            cmds.confirmDialog(title="SMPL-X prerequisite",message=str(exc),button=["OK"])
    cmds.button(label="2  CHECK SMPL-X MODEL FILES",command=check_models)
    def check_eos(*_):
        s=status()
        cmds.confirmDialog(title="EOS status",message="eos Python: {}\nEOS binary: {}".format(
            s["eos_python"],s["eos_fit_model"]),button=["OK"])
    cmds.button(label="3  CHECK EOS INSTALLATION",command=check_eos)
    def check_mgear(*_):
        cmds.confirmDialog(title="mGear status",message=str(mgear_status()),button=["OK"])
    cmds.button(label="4  CHECK mGEAR INSTALLATION",command=check_mgear)
    cmds.text(label="EOS face fitting requires photo + iBUG landmarks + model files.",align="center")
    cmds.text(label="SMPL-X fitting and mGear autorig require separate setup; not automated yet.",
              align="center")
    cmds.showWindow(win)
    return win
